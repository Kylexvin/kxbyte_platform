const exportSales = async (organizationId, startDate, endDate, branchId = null) => {
  const where = {
    organizationId,
    status: 'COMPLETED',
    createdAt: {
      gte: new Date(startDate),
      lte: new Date(endDate),
    },
  };

  if (branchId) {
    where.branchId = branchId;
  }

  const sales = await prisma.kxTillSale.findMany({
    where,
    include: {
      items: {
        include: {
          product: true,
        },
      },
      user: {
        select: {
          firstName: true,
          lastName: true,
        },
      },
      branch: {
        select: {
          name: true,
        },
      },
      payments: {
        select: {
          method: true,
        },
        take: 1,
      },
    },
    orderBy: { createdAt: 'desc' },
  });

  const flatData = [];
  for (const sale of sales) {
    for (const item of sale.items) {
      flatData.push({
        'Sale ID': sale.id.slice(0, 8).toUpperCase(),
        'Date': formatDate(sale.createdAt),
        'Time': new Date(sale.createdAt).toLocaleTimeString(),
        'Branch': sale.branch?.name || 'Main',
        'Attendant': `${sale.user?.firstName || ''} ${sale.user?.lastName || ''}`.trim(),
        'Product': item.product?.name || 'Unknown',
        'Quantity': Number(item.quantity),
        'Unit': item.unitAbbrev || '',
        'Unit Price': Number(item.unitPrice),
        'Total': Number(item.total),
        'Sale Total': Number(sale.totalAmount),
        'Payment Method': sale.payments?.[0]?.method || 'CASH',
      });
    }
  }

  return flatData;
};

