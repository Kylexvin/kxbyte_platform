// ============================================================

const exportBranchPerformance = async (organizationId, startDate, endDate) => {
  const branches = await prisma.branch.findMany({
    where: { organizationId, isActive: true },
    include: {
      sales: {
        where: {
          status: 'COMPLETED',
          createdAt: {
            gte: new Date(startDate),
            lte: new Date(endDate),
          },
        },
        select: {
          totalAmount: true,
          items: {
            select: {
              quantity: true,
            },
          },
        },
      },
    },
  });

  return branches.map((branch) => {
    const totalSales = branch.sales.reduce((sum, s) => sum + Number(s.totalAmount), 0);
    const totalItems = branch.sales.reduce((sum, s) => sum + s.items.reduce((acc, i) => acc + Number(i.quantity), 0), 0);
    const saleCount = branch.sales.length;

    return {
      'Branch': branch.name,
      'Total Sales': formatCurrency(totalSales),
      'Sale Count': saleCount,
      'Items Sold': totalItems,
      'Average Sale': saleCount > 0 ? formatCurrency(totalSales / saleCount) : formatCurrency(0),
    };
  });
};

