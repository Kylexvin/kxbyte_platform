const exportStock = async (organizationId, branchId = null) => {
  const where = {
    organizationId,
    isActive: true,
  };

  const products = await prisma.kxTillProduct.findMany({
    where,
    include: {
      units: true,
      baseUnit: true,
      branchProducts: {
        where: branchId ? { branchId } : {},
        include: {
          branch: {
            select: { name: true },
          },
        },
      },
    },
    orderBy: { name: 'asc' },
  });

  const flatData = [];
  for (const product of products) {
    const branchStock = product.branchProducts.length > 0
      ? product.branchProducts
      : [{ stock: 0, minStock: 0, branch: { name: 'All Branches' } }];

    for (const bp of branchStock) {
      flatData.push({
        'Product': product.name,
        'SKU': product.sku || '-',
        'Category': product.category || '-',
        'Branch': bp.branch?.name || 'All',
        'Stock': Number(bp.stock),
        'Min Stock': Number(bp.minStock),
        'Status': bp.stock <= bp.minStock ? 'Low Stock' : 'OK',
        'Unit': product.baseUnit?.abbreviation || 'units',
      });
    }
  }

  return flatData;
};

