// ============================================================

const exportTax = async (organizationId, startDate, endDate) => {
  const sales = await prisma.kxTillSale.findMany({
    where: {
      organizationId,
      status: 'COMPLETED',
      createdAt: {
        gte: new Date(startDate),
        lte: new Date(endDate),
      },
    },
    include: {
      items: {
        include: {
          product: true,
        },
      },
      branch: {
        select: { name: true },
      },
    },
    orderBy: { createdAt: 'asc' },
  });

  const flatData = [];
  let totalTax = 0;

  for (const sale of sales) {
    for (const item of sale.items) {
      const tax = Number(item.taxAmount) || 0;
      totalTax += tax;
      flatData.push({
        'Date': formatDate(sale.createdAt),
        'Branch': sale.branch?.name || 'Main',
        'Product': item.product?.name || 'Unknown',
        'Quantity': Number(item.quantity),
        'Total': Number(item.total),
        'Tax Rate': `${Number(item.taxRate)}%`,
        'Tax Amount': tax,
      });
    }
  }

  return {
    items: flatData,
    summary: {
      'Total Tax Collected': formatCurrency(totalTax),
      'Total Sales': sales.length,
      'Total Items': flatData.length,
      'Period': `${formatDate(startDate)} - ${formatDate(endDate)}`,
    },
  };
};

