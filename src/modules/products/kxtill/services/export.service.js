const generatePDF = (data, title) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 30, size: 'A4' });
      const chunks = [];

      doc.on('data', (chunk) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));

      doc.fontSize(18).text(title, { align: 'center' });
      doc.moveDown();
      doc.fontSize(10).text(`Generated: ${new Date().toLocaleString()}`, { align: 'right' });
      doc.moveDown();

      if (!data || data.length === 0) {
        doc.fontSize(12).text('No data available');
        doc.end();
        return;
      }

      const headers = Object.keys(data[0]);
      const pageWidth = doc.page.width - 60;
      const colWidth = Math.min(80, pageWidth / headers.length);
      const tableWidth = headers.length * colWidth;
      const tableLeft = (doc.page.width - tableWidth) / 2;

      let rowY = doc.y + 10;

      doc.fontSize(9).font('Helvetica-Bold');
      headers.forEach((header, i) => {
        const x = tableLeft + i * colWidth;
        doc.text(header, x, rowY, { width: colWidth, align: 'left' });
      });

      doc.fontSize(8).font('Helvetica');
      rowY += 18;

      for (const row of data) {
        headers.forEach((header, i) => {
          const x = tableLeft + i * colWidth;
          const value = row[header] !== undefined && row[header] !== null ? String(row[header]) : '';
          doc.text(value, x, rowY, { width: colWidth, align: 'left' });
        });
        rowY += 16;

        if (rowY > doc.page.height - 40) {
          doc.addPage();
          rowY = 30;
          doc.fontSize(9).font('Helvetica-Bold');
          headers.forEach((header, i) => {
            const x = tableLeft + i * colWidth;
            doc.text(header, x, rowY, { width: colWidth, align: 'left' });
          });
          doc.fontSize(8).font('Helvetica');
          rowY += 18;
        }
      }

      doc.moveDown();
      doc.fontSize(8).text(`Generated by KXBYTE • ${new Date().toLocaleString()}`, {
        align: 'center',
        color: '#999999',
      });

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};

