const exportTopProducts = async (organizationId, startDate, endDate, limit = 50) => {
  const takeLimit = typeof limit === 'string' ? parseInt(limit, 10) || 50 : limit || 50;

  const topProducts = await prisma.kxTillSaleItem.groupBy({
    by: ['productId'],
    where: {
      sale: {
        organizationId,
        status: 'COMPLETED',
        createdAt: {
          gte: new Date(startDate),
          lte: new Date(endDate),
        },
      },
    },
    _sum: {
      total: true,
      quantity: true,
    },
    orderBy: {
      _sum: {
        total: 'desc',
      },
    },
    take: takeLimit,
  });

  const productIds = topProducts.map((p) => p.productId);
  const products = await prisma.kxTillProduct.findMany({
    where: { id: { in: productIds } },
    select: {
      id: true,
      name: true,
      sku: true,
      category: true,
    },
  });

  const productMap = Object.fromEntries(products.map((p) => [p.id, p]));

  return topProducts.map((p) => {
    const product = productMap[p.productId];
    return {
      'Product': product?.name || 'Unknown',
      'SKU': product?.sku || '-',
      'Category': product?.category || '-',
      'Total Revenue': formatCurrency(p._sum.total || 0),
      'Quantity Sold': Number(p._sum.quantity || 0),
    };
  });
};

